"""The key map: what every key does on every page, with the cursor at each kind of place, gathered by the key tour of
test/test_tui_help_keys.py and written into .claude/KEYMAP.md, which TestKeyMapIsCurrent keeps current and
internal_tools/key_map.sh rewrites. It's for Claude, so that a question about a key is one lookup, the user's ask."""

import os

from llamatron.tui.screens.arrange_page import ArrangePage
from llamatron.tui.screens.field import Button, Heading
from llamatron.tui.screens.field_page import FieldPage
from llamatron.tui.screens.list_page import ListPage
from llamatron.tui.screens.pattern_editor import PatternEditor
from llamatron.tui import keybindings


KEY_MAP_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), '.claude', 'KEYMAP.md')
WRITE_KEY_MAP = 'LLAMATRON_WRITE_KEY_MAP'
FILE_ENCODING = 'utf-8'

# The words for each kind of place a cursor can be.
ANYWHERE = 'anywhere'
A_ROW = 'a row'
THE_PLUS_ROW = 'the + row'
SEARCHING = 'while searching'
MOVING = 'Move mode'
THE_CORNER = 'the corner'
A_TRACK_NAME = "a track's name"
THE_TRACK_PLUS = 'the + after the tracks'
A_SCENE_NAME = "a scene's name"
A_CLIP = 'a clip'
AN_EMPTY_CELL = 'an empty cell'
A_LOCKED_CELL = 'a locked cell'
SCENE_VIEW = 'Scene View'
THE_ROLL = 'the piano roll'
ROW_PLACE = 'the {row} row'
FIELD_PLACE = 'the {label} field'
HEADING_PLACE = 'the {label} heading'
BUTTON_PLACE = 'the {label} button'
WHILE_TYPING = 'while typing'

HEADER = """# Key Map

Generated by `internal_tools/key_map.sh` from the key tour in `test/test_tui_help_keys.py`; never edit it by hand.
`test/test_tui_help_keys.py`'s `TestKeyMapIsCurrent` fails when it's out of date. It says what every key does on every
page, with the cursor at each kind of place the tour reaches, then which pages and places use each key, then every
settings page's fields. The keys that work everywhere are listed once:

{everywhere}
"""
PAGE_HEADING = '\n## {page}\n'
PLACE_LINE = '- **{places}**: {keys}'
KEY_ENTRY = '`{key}` {what}'
KEY_SEPARATOR = ' · '
PLACE_SEPARATOR = ', '
INDEX_HEADING = '\n# Each Key\n'
INDEX_KEY_HEADING = '\n## `{key}`\n'
INDEX_LINE = '- {page}: {what} ({places})'
FIELDS_HEADING = '\n# Settings Pages\n'
FIELDS_LINE = '- **{page}**: {fields}'
FIELD_SEPARATOR = ', '
HEADING_SHOWN = '[{label}]'
BUTTON_SHOWN = '({label})'


def place_of(page):
    """Return the words for where the page's cursor is, for the key map."""
    if getattr(page, 'searching', False):
        return SEARCHING
    if getattr(page, 'moving', None):
        return MOVING
    if page.takes_text():
        return WHILE_TYPING
    if isinstance(page, ArrangePage):
        return arrange_place(page)
    if isinstance(page, PatternEditor):
        return THE_ROLL if page.view() is page.roll else ROW_PLACE.format(row=page.row_name())
    if isinstance(page, FieldPage):
        fields = page.shown_fields()
        if not fields:
            return ANYWHERE
        field = fields[min(page.place, len(fields) - 1)]
        if isinstance(field, Heading):
            return HEADING_PLACE.format(label=field.label)
        if isinstance(field, Button):
            return BUTTON_PLACE.format(label=field.label)
        return FIELD_PLACE.format(label=field.label)
    if isinstance(page, ListPage):
        return THE_PLUS_ROW if page.current() is None else A_ROW
    return ANYWHERE


def arrange_place(page):
    if page.inset is not None:
        return SCENE_VIEW
    if page.picking():
        return A_LOCKED_CELL
    if page.on_corner():
        return THE_CORNER
    if page.on_track_plus():
        return THE_TRACK_PLUS
    if page.on_header():
        return A_TRACK_NAME
    if page.on_plus_row():
        return THE_PLUS_ROW
    if page.on_scene_name():
        return A_SCENE_NAME
    return A_CLIP if page.document().clip_slot(index=page.row, track=page.track()) is not None else AN_EMPTY_CELL


class KeyMap:
    """What the tour found: each page's key tables by place, and each settings page's fields."""

    __slots__ = ('tables', 'fields')

    def __init__(self):
        self.tables = {}
        self.fields = {}

    def note(self, page):
        """Keep the keys the page binds where its cursor is now, leaving out the ones that work everywhere."""
        everywhere = {binding for binding in keybindings.Page.EVERYWHERE}
        entries = tuple((item.label, item.what) for item in page.key_table() if item.binding not in everywhere)
        places = self.tables.setdefault(type(page).__name__, {})
        places.setdefault(entries, [])
        place = place_of(page)
        if place not in places[entries]:
            places[entries].append(place)
        if isinstance(page, FieldPage) and type(page).__name__ not in self.fields:
            self.fields[type(page).__name__] = [field_shown(field) for field in page.fields()]

    def text(self, *, everywhere):
        lines = [HEADER.format(everywhere=everywhere)]
        index = {}
        for page in sorted(self.tables):
            lines.append(PAGE_HEADING.format(page=page))
            for entries, places in self.tables[page].items():
                shown_places = PLACE_SEPARATOR.join(places)
                lines.append(PLACE_LINE.format(places=shown_places, keys=KEY_SEPARATOR.join(KEY_ENTRY.format(key=key, what=what) for key, what in entries)))
                for key, what in entries:
                    meanings = index.setdefault(key, {}).setdefault((page, what), [])
                    meanings += [place for place in places if place not in meanings]
        lines.append(INDEX_HEADING)
        for key in sorted(index, key=str.lower):
            lines.append(INDEX_KEY_HEADING.format(key=key))
            lines += [INDEX_LINE.format(page=page, what=what, places=PLACE_SEPARATOR.join(places)) for (page, what), places in index[key].items()]
        lines.append(FIELDS_HEADING)
        for page in sorted(self.fields):
            lines.append(FIELDS_LINE.format(page=page, fields=FIELD_SEPARATOR.join(self.fields[page])))
        return '\n'.join(lines) + '\n'


def field_shown(field):
    if isinstance(field, Heading):
        return HEADING_SHOWN.format(label=field.label)
    if isinstance(field, Button):
        return BUTTON_SHOWN.format(label=field.label)
    return field.label


def written_key_map():
    """Return what .claude/KEYMAP.md holds, or None when it doesn't exist yet."""
    if not os.path.exists(KEY_MAP_PATH):
        return None
    with open(KEY_MAP_PATH, encoding=FILE_ENCODING) as handle:
        return handle.read()


def write_key_map(text):
    with open(KEY_MAP_PATH, 'w', encoding=FILE_ENCODING) as handle:
        handle.write(text)


def should_write():
    """Return whether the run is internal_tools/key_map.sh's, which writes the map rather than checking it."""
    return bool(os.environ.get(WRITE_KEY_MAP))
