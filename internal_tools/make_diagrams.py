"""Writes the diagrams in docs/ARCHITECTURE.md and docs/GETTING_STARTED.md from the code, as Mermaid that GitHub draws.

Run from the top folder:

    .venv/bin/python internal_tools/make_diagrams.py            # rewrite every diagram in place
    .venv/bin/python internal_tools/make_diagrams.py --check    # say which diagrams are out of date, and fail if any is

Each diagram sits between a pair of marker comments in its document, and only the text between
them is replaced, so the words around a diagram can be edited by hand. The packages diagram
comes from the imports between llamatron's packages, with each package described by the first
line of its __init__.py docstring. The screens diagram comes from which of the tracker's screens
open which others, labelled with the key that opens each where the screen binds it with bind().
A screen that tui/screens/everywhere.py opens from every page is drawn from the main screen.
test/test_diagrams.py runs the check, so a change to the code that moves a diagram fails the
tests until this is run again.
"""

import ast
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'src' / 'llamatron'
ARCHITECTURE = ROOT / 'docs' / 'ARCHITECTURE.md'
GETTING_STARTED = ROOT / 'docs' / 'GETTING_STARTED.md'
PACKAGE = 'llamatron'
SCREENS_PACKAGE = 'tui.screens'
PACKAGE_FILE = '__init__.py'
PYTHON_SUFFIX = '.py'
PYTHON_FILES = '*' + PYTHON_SUFFIX
DOT = '.'
LINE_BREAK = '\n'
FILE_ENCODING = 'utf-8'
CHECK_OPTION = '--check'

# The marker comments a diagram sits between, in the document that holds it.
MARKER_START = '<!-- generated by internal_tools/make_diagrams.py: {name} -->'
MARKER_END = '<!-- end of the generated diagram -->'
DIAGRAM_PACKAGES = 'packages'
DIAGRAM_SCREENS = 'screens'

# Mermaid, which GitHub draws from a fenced block.
FENCE_START = '```mermaid'
FENCE_END = '```'
FLOWCHART = 'flowchart {direction}'
LEFT_TO_RIGHT = 'LR'
TOP_DOWN = 'TD'
NODE = '    {id}["{label}"]'
EDGE = '    {source} --> {target}'
LABELLED_EDGE = '    {source} -- "{label}" --> {target}'
SUBGRAPH_START = '    subgraph {id} ["{label}"]'
SUBGRAPH_END = '    end'
MAIN_SCREEN_ID = 'MainPage'
# The module whose keys work on every page, so the screens it opens are drawn from the main screen.
EVERYWHERE_MODULE = 'everywhere'
# The class every screen descends from, which is how the screens are told from the other classes beside them.
SCREEN_BASE = 'Page'
# Screens whose names in words aren't just their class names split up.
SCREEN_LABELS = {
    MAIN_SCREEN_ID: 'Main screen',
    'ArpEditor': 'Arpeggiator editor',
    'AutoRatchetEditor': 'AutoRatchet editor',
    'FilePage': 'Set File',
}
PAGE_SUFFIX = 'Page'
EDITOR_SUFFIX = 'Editor'
EDITOR_WORD = ' editor'
CAMEL_CASE_BOUNDARY = re.compile(r'(?<=[a-z])(?=[A-Z])')
WORD_SEPARATOR = ' '
# A screen binds a key with self.bind(self.KEYS.NAME, action=...), where KEYS is its class of tui/keybindings.py.
BIND_METHOD = 'bind'
PAGE_BINDINGS = 'Page'
# A settings field whose Enter opens a screen, like the File page's Description.
FIELD_FUNCTION = 'Field'
ENTER_ARGUMENT = 'enter'
SELF = 'self'
ACTION_ARGUMENT = 'action'

# The packages table under the diagram.
TABLE_HEADER = '| Package | What it holds |'
TABLE_RULE = '| --- | --- |'
TABLE_ROW = '| `{name}` | {description} |'
NO_DESCRIPTION = ''

# How the packages are grouped: the top level is the loose modules beside the packages, and the
# packages everything uses sit in their own box with no arrows, so that the arrows show the flow
# of a song rather than a web. The strings package holds only words,
# so it sits in that box too, and the names it imports to build its tables aren't drawn as arrows.
TOP_LEVEL = 'llamatron'
USED_EVERYWHERE = ['music', 'support', 'strings']
USED_EVERYWHERE_ID = 'everywhere'
USED_EVERYWHERE_LABEL = 'used by every other part'
TEXT_PACKAGE = 'strings'
# Packages in the order a reader meets them, following a song from the tracker to the files.
PACKAGE_ORDER = ['tui', 'llamatron', 'composition', 'playback', 'generators', 'grid', 'exporters']

MSG_NO_MARKER = 'no marker ({marker}) in {path}'
MSG_OUT_OF_DATE = 'out of date: the {name} diagram in {path}'
MSG_UP_TO_DATE = 'up to date: the {name} diagram in {path}'
MSG_WRITTEN = 'wrote the {name} diagram in {path}'
MSG_RUN_AGAIN = 'run internal_tools/make_diagrams.py to update them'
FAILURE = 1
SUCCESS = 0


def module_name(path):
    """Return a source file's dotted module name, like llamatron.tui.screens.song_page."""
    parts = path.relative_to(SOURCE.parent).with_suffix(NO_DESCRIPTION).parts
    if parts[-1] == PACKAGE_FILE[:-len(PYTHON_SUFFIX)]:
        parts = parts[:-1]
    return DOT.join(parts)


def package_of(name):
    """Return the package a module belongs to for the diagram: its first folder, or the top level."""
    parts = name.split(DOT)
    if len(parts) > 2:
        return parts[1]
    return TOP_LEVEL


def source_files():
    return sorted(SOURCE.rglob(PYTHON_FILES))


def parsed(path):
    return ast.parse(path.read_text(encoding=FILE_ENCODING))


def is_package(name):
    """Return whether a dotted name is one of llamatron's packages, a folder, rather than a module."""
    return SOURCE.parent.joinpath(*name.split(DOT)).is_dir()


def modules_of(node):
    """Return the modules one import statement names: the module imported from, or each module taken from a package, as in from llamatron.tui import keybindings."""
    if is_package(node.module):
        return [node.module + DOT + alias.name for alias in node.names]
    return [node.module]


def imported_modules(tree):
    """Return the llamatron modules a parsed file imports from."""
    imports = [node for node in ast.walk(tree) if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith(PACKAGE)]
    return [name for node in imports for name in modules_of(node)]


def package_description(name):
    """Return the first line of a package's docstring, or the top level's."""
    folder = SOURCE if name == TOP_LEVEL else SOURCE / name
    docstring = ast.get_docstring(parsed(folder / PACKAGE_FILE))
    if not docstring:
        return NO_DESCRIPTION
    return docstring.splitlines()[0]


def packages_and_edges():
    """Return the packages in reading order and the (user, used) pairs between them."""
    packages = set()
    edges = set()
    for path in source_files():
        user = package_of(module_name(path))
        packages.add(user)
        if user == TEXT_PACKAGE:
            continue
        for imported in imported_modules(parsed(path)):
            used = package_of(imported)
            packages.add(used)
            if used != user:
                edges.add((user, used))
    ordered = [name for name in PACKAGE_ORDER if name in packages]
    ordered += sorted(packages - set(ordered) - set(USED_EVERYWHERE))
    ordered += [name for name in USED_EVERYWHERE if name in packages]
    return ordered, sorted(edges)


def packages_diagram():
    """Return the Mermaid block and table for the packages and the imports between them."""
    packages, edges = packages_and_edges()
    lines = [FENCE_START, FLOWCHART.format(direction=LEFT_TO_RIGHT)]
    for name in packages:
        if name not in USED_EVERYWHERE:
            lines.append(NODE.format(id=name, label=name))
    lines.append(SUBGRAPH_START.format(id=USED_EVERYWHERE_ID, label=USED_EVERYWHERE_LABEL))
    for name in packages:
        if name in USED_EVERYWHERE:
            lines.append(NODE.format(id=name, label=name))
    lines.append(SUBGRAPH_END)
    for user, used in edges:
        if used not in USED_EVERYWHERE:
            lines.append(EDGE.format(source=user, target=used))
    lines.append(FENCE_END)
    lines.append(NO_DESCRIPTION)
    lines.append(TABLE_HEADER)
    lines.append(TABLE_RULE)
    for name in packages:
        lines.append(TABLE_ROW.format(name=name, description=package_description(name)))
    return LINE_BREAK.join(lines)


def screen_label(class_name):
    """Return a screen's name in words: SongPage is Song, PatternEditor is Pattern editor."""
    if class_name in SCREEN_LABELS:
        return SCREEN_LABELS[class_name]
    if class_name.endswith(PAGE_SUFFIX):
        words = class_name[:-len(PAGE_SUFFIX)]
    elif class_name.endswith(EDITOR_SUFFIX):
        words = class_name[:-len(EDITOR_SUFFIX)] + EDITOR_WORD
    else:
        words = class_name
    return CAMEL_CASE_BOUNDARY.sub(WORD_SEPARATOR, words).capitalize()


def screen_modules():
    """Return (module name, parsed file) for every screen of the tracker."""
    folder = SOURCE.joinpath(*SCREENS_PACKAGE.split(DOT))
    return [(module_name(path), parsed(path)) for path in sorted(folder.glob(PYTHON_FILES))]


def base_names(class_node):
    return [base.id for base in class_node.bases if isinstance(base, ast.Name)]


def screen_classes(trees):
    """Return the classes that are screens: Page and everything that descends from it."""
    classes = [node for tree in trees for node in ast.walk(tree) if isinstance(node, ast.ClassDef)]
    screens = {SCREEN_BASE}
    found_more = True
    while found_more:
        more = {node.name for node in classes if node.name not in screens and set(base_names(node)) & screens}
        screens |= more
        found_more = bool(more)
    return screens


def screens_built(*, node, screens):
    """Return the screen classes a piece of code builds, which is how a screen opens another."""
    return {call.func.id for call in ast.walk(node) if isinstance(call, ast.Call) and isinstance(call.func, ast.Name) and call.func.id in screens}


def keyword(*, call, name):
    return next((item.value for item in call.keywords if item.arg == name), None)


def enter_key_label():
    """Return how the tracker shows the Enter key, which opens a screen from a settings field."""
    from llamatron.tui import keybindings
    _, name, _ = keybindings.FieldPage.ENTER
    return name


def is_binding(call):
    """Return whether a call binds a key, as self.bind(self.KEYS.NAME, action=...) does."""
    return isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute) and call.func.attr == BIND_METHOD and bool(call.args)


def shown_key(*, binding, class_name):
    """Return how the tracker shows the keys of a binding named like self.KEYS.NAME, in a class's bindings, or None if it can't be read."""
    from llamatron.tui import keybindings
    if not isinstance(binding, ast.Attribute):
        return None
    found = getattr(getattr(keybindings, class_name, None), binding.attr, None)
    if found is None:
        return None
    _, name, _ = found
    return name


def own_method(*, expression, methods):
    """Return the class's method an expression like self.edit_description names, or None."""
    if isinstance(expression, ast.Attribute) and isinstance(expression.value, ast.Name) and expression.value.id == SELF:
        return methods.get(expression.attr)
    return None


def lambdas_by_name(function):
    """Return the screens each lambda assigned to a name in a function builds, by the name."""
    found = {}
    for node in ast.walk(function):
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Lambda) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            found[node.targets[0].id] = node.value
    return found


def openings(*, class_node, screens):
    """Return {opened screen: key label or None} for every screen a screen class opens."""
    opened = {}
    methods = {node.name: node for node in class_node.body if isinstance(node, ast.FunctionDef)}
    for function in methods.values():
        lambdas = lambdas_by_name(function)
        for call in ast.walk(function):
            if not is_binding(call):
                continue
            targets = screens_built(node=call, screens=screens)
            action = keyword(call=call, name=ACTION_ARGUMENT)
            if isinstance(action, ast.Name) and action.id in lambdas:
                targets |= screens_built(node=lambdas[action.id], screens=screens)
            label = shown_key(binding=call.args[0], class_name=class_node.name)
            for target in targets:
                opened[target] = label if label is not None else opened.get(target)
        for call in ast.walk(function):
            if isinstance(call, ast.Call) and isinstance(call.func, ast.Name) and call.func.id == FIELD_FUNCTION:
                enter = keyword(call=call, name=ENTER_ARGUMENT)
                for target in screens_built(node=own_method(expression=enter, methods=methods) or enter or call, screens=screens):
                    opened[target] = enter_key_label()
        for target in screens_built(node=function, screens=screens):
            opened.setdefault(target, None)
    opened.pop(class_node.name, None)
    return opened


def everywhere_openings(*, tree, screens):
    """Return {opened screen: key label} for the screens everywhere.py opens from every page: each entry of a dictionary of actions by binding, like keys.OPEN_SET: lambda: open_set(page)."""
    functions = {node.name: node for node in tree.body if isinstance(node, ast.FunctionDef)}
    opened = {}
    for table in [node for node in ast.walk(tree) if isinstance(node, ast.Dict)]:
        for binding, action in zip(table.keys, table.values):
            label = shown_key(binding=binding, class_name=PAGE_BINDINGS)
            if label is None:
                continue
            targets = screens_built(node=action, screens=screens)
            for called in functions_called(node=action, functions=functions):
                targets |= screens_built(node=called, screens=screens)
            for target in targets:
                opened[target] = label
    return opened


def functions_called(*, node, functions):
    """Return the module's functions that a piece of code calls by name, such as the action a key's lambda runs."""
    if node is None:
        return []
    return [functions[call.func.id] for call in ast.walk(node) if isinstance(call, ast.Call) and isinstance(call.func, ast.Name) and call.func.id in functions]


def screens_and_openings():
    """Return the screens that are opened, in order from the main screen, and {(opener, opened): key}."""
    modules = screen_modules()
    screens = screen_classes([tree for _, tree in modules])
    edges = {}
    for name, tree in modules:
        if name.rsplit(DOT, 1)[-1] == EVERYWHERE_MODULE:
            for target, label in everywhere_openings(tree=tree, screens=screens).items():
                edges[(MAIN_SCREEN_ID, target)] = label
        for class_node in [node for node in tree.body if isinstance(node, ast.ClassDef)]:
            for target, label in openings(class_node=class_node, screens=screens).items():
                edges[(class_node.name, target)] = label
    ordered = [MAIN_SCREEN_ID]
    for opener in ordered:
        for (source, target), _ in sorted(edges.items()):
            if source == opener and target not in ordered:
                ordered.append(target)
    return ordered, edges


def screens_diagram():
    """Return the Mermaid block of the tracker's screens and which opens which."""
    ordered, edges = screens_and_openings()
    lines = [FENCE_START, FLOWCHART.format(direction=TOP_DOWN)]
    for name in ordered:
        lines.append(NODE.format(id=name, label=screen_label(name)))
    for (source, target), label in sorted(edges.items()):
        if source in ordered and target in ordered:
            if label is None:
                lines.append(EDGE.format(source=source, target=target))
            else:
                lines.append(LABELLED_EDGE.format(source=source, target=target, label=label))
    lines.append(FENCE_END)
    return LINE_BREAK.join(lines)


DIAGRAMS = [
    (ARCHITECTURE, DIAGRAM_PACKAGES, packages_diagram),
    (GETTING_STARTED, DIAGRAM_SCREENS, screens_diagram),
]


def with_diagram(*, text, name, diagram, path):
    """Return a document's text with the diagram between its markers replaced."""
    start = MARKER_START.format(name=name)
    if start not in text or MARKER_END not in text[text.index(start):]:
        raise SystemExit(MSG_NO_MARKER.format(marker=start, path=path.relative_to(ROOT)))
    head = text[:text.index(start) + len(start)]
    tail = text[text.index(MARKER_END, len(head)):]
    return head + LINE_BREAK + diagram + LINE_BREAK + tail


def main(arguments):
    check_only = CHECK_OPTION in arguments
    stale = False
    for path, name, make in DIAGRAMS:
        text = path.read_text(encoding=FILE_ENCODING)
        updated = with_diagram(text=text, name=name, diagram=make(), path=path)
        if updated == text:
            print(MSG_UP_TO_DATE.format(name=name, path=path.relative_to(ROOT)))
        elif check_only:
            print(MSG_OUT_OF_DATE.format(name=name, path=path.relative_to(ROOT)))
            stale = True
        else:
            path.write_text(updated, encoding=FILE_ENCODING)
            print(MSG_WRITTEN.format(name=name, path=path.relative_to(ROOT)))
    if stale:
        print(MSG_RUN_AGAIN)
        return FAILURE
    return SUCCESS


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
