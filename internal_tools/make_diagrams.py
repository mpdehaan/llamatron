"""Write the architecture diagram from the code, so that it cannot go out of date: every crate of the Cargo workspace in
src/, an arrow where one uses another as its manifest says, and a table of each crate's folder, the first sentence it says
of itself in its own documentation, and its modules.

    .venv/bin/python internal_tools/make_diagrams.py            # rewrite the diagram in developer_docs/ARCHITECTURE.md
    .venv/bin/python internal_tools/make_diagrams.py --check    # exit 1 where the diagram is out of date

The diagram sits between its markers, and everything around them is left as it is.
"""

import argparse
import pathlib
import re
import sys

TOP = pathlib.Path(__file__).resolve().parent.parent
WORKSPACE = TOP / 'src'
DOCUMENT = TOP / 'developer_docs' / 'ARCHITECTURE.md'
START = '<!-- generated by internal_tools/make_diagrams.py: crates -->'
END = '<!-- end of the generated diagram -->'
CRATE_PREFIX = 'llamatron-'
# The order the crates are listed in: from the bottom layer up, each before the crates that use it.
FILE_ENCODING = 'utf-8'
CRATE_NAME = re.compile(r'^name\s*=\s*"([^"]+)"', re.MULTILINE)
DEPENDENCY = re.compile(r'^(llamatron-[a-z]+)\s*=', re.MULTILINE)
MODULE = re.compile(r'^pub mod ([a-z_]+);|^mod ([a-z_]+);', re.MULTILINE)
SENTENCE_END = re.compile(r'(?<=[.!?])\s')


def crates():
    """Return each crate of the workspace as (its folder's name, its package name, the crates it uses, its first sentence,
    its modules), ordered so that a crate comes after every crate it uses."""
    found = {}
    for manifest in sorted(WORKSPACE.glob('*/Cargo.toml')):
        text = manifest.read_text(encoding=FILE_ENCODING)
        name = CRATE_NAME.search(text).group(1)
        dependencies = section_of(text, '[dependencies]')
        uses = sorted(set(DEPENDENCY.findall(dependencies)))
        root = manifest.parent / 'src' / 'lib.rs'
        if not root.exists():
            root = manifest.parent / 'src' / 'main.rs'
        source = root.read_text(encoding=FILE_ENCODING)
        modules = [public or private for public, private in MODULE.findall(source)]
        found[name] = (manifest.parent.name, name, uses, first_sentence(source), modules)
    ordered = []
    while len(ordered) < len(found):
        for name, crate in sorted(found.items()):
            if name not in [each[1] for each in ordered] and all(use in [each[1] for each in ordered] or use not in found for use in crate[2]):
                ordered.append(crate)
                break
    return ordered


def section_of(text, heading):
    """Return the lines of a manifest's section, from its heading to the next."""
    if heading not in text:
        return ''
    after = text.split(heading, 1)[1]
    return after.split('\n[', 1)[0]


def first_sentence(source):
    """Return the first sentence of a file's own documentation, its //! lines."""
    lines = [line[3:].strip() for line in source.splitlines() if line.startswith('//!')]
    paragraph = []
    for line in lines:
        if not line:
            break
        paragraph.append(line)
    return SENTENCE_END.split(' '.join(paragraph), maxsplit=1)[0]


def diagram():
    """Return the diagram and its table, as the markdown between the markers."""
    found = crates()
    lines = [START, '```mermaid', 'flowchart TD']
    for folder, name, _, _, _ in found:
        lines.append('    {}["{}"]'.format(folder, name.removeprefix(CRATE_PREFIX)))
    for folder, _, uses, _, _ in reversed(found):
        for use in uses:
            used = next((each[0] for each in found if each[1] == use), None)
            if used is not None:
                lines.append('    {} --> {}'.format(folder, used))
    lines += ['```', '', '| Crate | Folder | What it holds | Modules |', '| --- | --- | --- | --- |']
    for folder, name, _, sentence, modules in found:
        shown = ', '.join('`{}`'.format(module) for module in modules)
        lines.append('| {} | `src/{}/` | {} | {} |'.format(name.removeprefix(CRATE_PREFIX), folder, sentence, shown))
    lines.append(END)
    return '\n'.join(lines)


def written(text):
    """Return a document with its diagram written again between the markers."""
    if START not in text or END not in text:
        raise SystemExit('{}: the diagram\'s markers are missing'.format(DOCUMENT))
    before = text.split(START, 1)[0]
    after = text.split(END, 1)[1]
    return before + diagram() + after


def main():
    made = argparse.ArgumentParser(description='Write the architecture diagram from the code.')
    made.add_argument('--check', action='store_true', help='exit 1 where the diagram is out of date, writing nothing')
    options = made.parse_args()
    text = DOCUMENT.read_text(encoding=FILE_ENCODING)
    new = written(text)
    if options.check:
        return 0 if new == text else 1
    DOCUMENT.write_text(new, encoding=FILE_ENCODING)
    print('wrote the diagram in {}'.format(DOCUMENT.relative_to(TOP)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
