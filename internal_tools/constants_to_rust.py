"""Write the Rust form of every text the program shows (native/strings/src/texts/), from the Python user_strings package itself,
so that llamatron2 shows each text character for character as llamatron does: a module a Python module, each constant of
the same name, a text a &str, a tuple or list a slice, a mapping a slice of (key, value) pairs in its order.

    .venv/bin/python internal_tools/strings_to_rust.py

The texts are templates for Python's str.format, which the Rust crate's fill() reads (native/strings/src/fill.rs). Run it
again after any text changes; the generated files say so at their top and are never edited by hand.
"""

import importlib
import inspect
import pathlib
import pkgutil
import sys

import llamatron.user_strings as package
from llamatron.model.schema import defaults, file_format, limits
from llamatron.model.values import midi
from llamatron.music_theory.fundamentals import chord_shapes, intervals, scale_shapes

TOP = pathlib.Path(__file__).resolve().parent.parent
OUT = TOP / 'native' / 'strings' / 'src' / 'texts'
SCHEMA_OUT = TOP / 'native' / 'model' / 'src' / 'schema' / 'generated'
SCHEMA_MODULES = (('file_format', file_format), ('limits', limits), ('defaults', defaults), ('midi', midi))
FUNDAMENTALS_OUT = TOP / 'native' / 'model' / 'src' / 'fundamentals' / 'generated'
FUNDAMENTALS_MODULES = (('intervals', intervals), ('scale_shapes', scale_shapes), ('chord_shapes', chord_shapes))
HEADER = '''// llamatron: a music program
// Copyright (C) 2026  Michael DeHaan
// SPDX-License-Identifier: GPL-3.0-or-later
//! Generated by internal_tools/constants_to_rust.py from the Python {source}; never edited by hand.

#![allow(dead_code)]
'''
TEXT = '&str'
# Constants holding rationals, an empty value or chord types, written by hand in the Rust model instead.
HAND_WRITTEN = {'GATE_MODIFIERS', 'ACCIDENTAL_CYCLE', 'FIXED_CHORDS', 'DOUBLED_NOTES'}


class NotWritable(Exception):
    """A value with no Rust form here."""


def literal(text):
    """Return a text as a Rust string literal, escaped as Rust reads it."""
    escaped = []
    for character in text:
        if character == '\\':
            escaped.append('\\\\')
        elif character == '"':
            escaped.append('\\"')
        elif character == '\n':
            escaped.append('\\n')
        elif character == '\t':
            escaped.append('\\t')
        elif character == '\r':
            escaped.append('\\r')
        elif ord(character) < 32:
            escaped.append('\\u{{{:x}}}'.format(ord(character)))
        else:
            escaped.append(character)
    return '"' + ''.join(escaped) + '"'


def written(value):
    """Return a value's Rust type and expression."""
    if isinstance(value, bool):
        return 'bool', 'true' if value else 'false'
    if isinstance(value, str):
        return TEXT, literal(value)
    if isinstance(value, int):
        return 'i64', str(value)
    if isinstance(value, float):
        return 'f64', repr(value) if '.' in repr(value) or 'e' in repr(value) else repr(value) + '.0'
    if isinstance(value, frozenset):
        value = sorted(value, key=repr)
    if isinstance(value, (tuple, list)):
        parts = [written(item) for item in value]
        kinds = {kind for kind, _ in parts}
        if len(kinds) > 1:
            raise NotWritable(value)
        kind = kinds.pop() if kinds else TEXT
        return '&[{}]'.format(kind), '&[' + ', '.join(expression for _, expression in parts) + ']'
    if isinstance(value, dict):
        pairs = [(written(key), written(item)) for key, item in value.items()]
        key_kinds = {key[0] for key, _ in pairs}
        if len(key_kinds) > 1:
            # Keys of numbers and texts together are all written as texts, which the Rust side looks them up by.
            pairs = [(written(str(key)), written(item)) for key, item in value.items()]
            key_kinds = {TEXT}
        value_kinds = {item[0] for _, item in pairs}
        if len(key_kinds) > 1 or len(value_kinds) > 1:
            raise NotWritable(value)
        key_kind = key_kinds.pop() if key_kinds else TEXT
        value_kind = value_kinds.pop() if value_kinds else TEXT
        body = ', '.join('({}, {})'.format(key[1], item[1]) for key, item in pairs)
        return '&[({}, {})]'.format(key_kind, value_kind), '&[' + body + ']'
    raise NotWritable(value)


def module_text(source, module):
    """Return a module's Rust form, and the names it could not write."""
    lines = [HEADER.format(source=source)]
    skipped = []
    for constant, value in vars(module).items():
        if constant.startswith('_'):
            continue
        if inspect.isclass(value) and value.__module__ == module.__name__:
            lines.extend(class_text(constant, value, skipped))
            continue
        if not constant.isupper() or constant in HAND_WRITTEN:
            continue
        try:
            kind, expression = written(value)
        except NotWritable:
            skipped.append(constant)
            continue
        if kind in (TEXT, 'i64', 'f64', 'bool'):
            lines.append('pub const {}: {} = {};'.format(constant, kind, expression))
        else:
            lines.append('pub static {}: {} = {};'.format(constant, kind, expression))
    return '\n'.join(lines) + '\n', skipped


def class_text(name, value, skipped):
    """Return a class of constants as a Rust type with the same associated constants."""
    members = []
    for inner, item in vars(value).items():
        if inner.startswith('_') or not inner.isupper():
            continue
        try:
            kind, expression = written(item)
        except NotWritable:
            skipped.append('{}.{}'.format(name, inner))
            continue
        # An associated constant's references are written 'static, as Rust asks of them.
        members.append('    pub const {}: {} = {};'.format(inner, kind.replace('&', "&'static "), expression))
    if not members:
        return []
    return ['pub struct {};'.format(name), '', 'impl {} {{'.format(name), *members, '}', '']


def write_modules(*, folder, modules):
    """Write each (name, module) into the folder, with a mod.rs naming them, and return the names each could not write."""
    folder.mkdir(parents=True, exist_ok=True)
    names = []
    unwritten = {}
    for name, module in modules:
        source = module.__name__.replace('.', '/').replace('llamatron', 'src/llamatron', 1) + '.py'
        text, skipped = module_text(source, module)
        (folder / '{}.rs'.format(name)).write_text(text)
        names.append(name)
        if skipped:
            unwritten[name] = skipped
    # Generated, so the formatter leaves them as written, and a new generation is never only a reformatting.
    modules_text = '\n'.join('#[rustfmt::skip]\npub mod {};'.format(name) for name in names)
    (folder / 'mod.rs').write_text(HEADER.format(source=folder.name) + '\n' + modules_text + '\n')
    return unwritten


def main():
    texts = [(info.name, importlib.import_module('llamatron.user_strings.' + info.name)) for info in pkgutil.iter_modules(package.__path__)]
    unwritten = write_modules(folder=OUT, modules=texts)
    unwritten.update(write_modules(folder=SCHEMA_OUT, modules=SCHEMA_MODULES))
    unwritten.update(write_modules(folder=FUNDAMENTALS_OUT, modules=FUNDAMENTALS_MODULES))
    for name, skipped in unwritten.items():
        print('{}: not written: {}'.format(name, ', '.join(skipped)), file=sys.stderr)


if __name__ == '__main__':
    main()
