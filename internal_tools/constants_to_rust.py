"""Write the Rust form of every text the program shows (native/strings/src/texts/), from the Python user_strings package itself,
so that llamatron2 shows each text character for character as llamatron does: a module a Python module, each constant of
the same name, a text a &str, a tuple or list a slice, a mapping a slice of (key, value) pairs in its order.

    .venv/bin/python internal_tools/strings_to_rust.py

The texts are templates for Python's str.format, which the Rust crate's fill() reads (native/strings/src/fill.rs). Run it
again after any text changes; the generated files say so at their top and are never edited by hand.
"""

import importlib
import inspect
import pathlib
import pkgutil
import sys

import llamatron.user_strings as package
from llamatron.model.schema import defaults, file_format, limits
from llamatron.model.values import midi, note as note_values, time_signature
from llamatron.model.values.chord import ChordType
from llamatron.model.values.scale import ScaleType
from llamatron.music_theory.fundamentals import chord_shapes, intervals, scale_shapes

TOP = pathlib.Path(__file__).resolve().parent.parent
OUT = TOP / 'native' / 'strings' / 'src' / 'texts'
SCHEMA_OUT = TOP / 'native' / 'model' / 'src' / 'schema' / 'generated'
SCHEMA_MODULES = (('file_format', file_format), ('limits', limits), ('defaults', defaults), ('midi', midi))
FUNDAMENTALS_OUT = TOP / 'native' / 'model' / 'src' / 'fundamentals' / 'generated'
FUNDAMENTALS_MODULES = (('intervals', intervals), ('scale_shapes', scale_shapes), ('chord_shapes', chord_shapes))
VALUES_OUT = TOP / 'native' / 'model' / 'src' / 'values' / 'generated'
VALUES_MODULES = (('note', note_values), ('time_signature', time_signature))
# The enums whose members' order and values the Rust model reads, each written as a list of (name, value) in order.
ENUMS = (('SCALE_TYPES', ScaleType), ('CHORD_TYPES', ChordType))
HEADER = '''// llamatron: a music program
// Copyright (C) 2026  Michael DeHaan
// SPDX-License-Identifier: GPL-3.0-or-later
//! Generated by internal_tools/constants_to_rust.py from the Python {source}; never edited by hand.

#![allow(dead_code)]
'''
TEXT = '&str'
# Constants holding rationals, an empty value or chord types, written by hand in the Rust model instead.
HAND_WRITTEN = {'GATE_MODIFIERS', 'ACCIDENTAL_CYCLE', 'FIXED_CHORDS', 'DOUBLED_NOTES', 'LENGTH_TYPES'}


class NotWritable(Exception):
    """A value with no Rust form here."""


def literal(text):
    """Return a text as a Rust string literal, escaped as Rust reads it."""
    escaped = []
    for character in text:
        if character == '\\':
            escaped.append('\\\\')
        elif character == '"':
            escaped.append('\\"')
        elif character == '\n':
            escaped.append('\\n')
        elif character == '\t':
            escaped.append('\\t')
        elif character == '\r':
            escaped.append('\\r')
        elif ord(character) < 32:
            escaped.append('\\u{{{:x}}}'.format(ord(character)))
        else:
            escaped.append(character)
    return '"' + ''.join(escaped) + '"'


def written(value):
    """Return a value's Rust type and expression."""
    if isinstance(value, bool):
        return 'bool', 'true' if value else 'false'
    if isinstance(value, str):
        return TEXT, literal(value)
    if isinstance(value, int):
        return 'i64', str(value)
    if isinstance(value, float):
        return 'f64', repr(value) if '.' in repr(value) or 'e' in repr(value) else repr(value) + '.0'
    if isinstance(value, frozenset):
        value = sorted(value, key=repr)
    if isinstance(value, (tuple, list)):
        parts = [written(item) for item in value]
        kinds = {kind for kind, _ in parts}
        if len(kinds) > 1 and isinstance(value, tuple):
            # A tuple of several kinds is a Rust tuple.
            return '(' + ', '.join(kind for kind, _ in parts) + ')', '(' + ', '.join(expression for _, expression in parts) + ')'
        if len(kinds) > 1:
            raise NotWritable(value)
        kind = kinds.pop() if kinds else TEXT
        return '&[{}]'.format(kind), '&[' + ', '.join(expression for _, expression in parts) + ']'
    if isinstance(value, dict):
        pairs = [(written(key), written(item)) for key, item in value.items()]
        key_kinds = {key[0] for key, _ in pairs}
        if len(key_kinds) > 1:
            # Keys of numbers and texts together are all written as texts, which the Rust side looks them up by.
            pairs = [(written(str(key)), written(item)) for key, item in value.items()]
            key_kinds = {TEXT}
        value_kinds = {item[0] for _, item in pairs}
        if len(key_kinds) > 1 or len(value_kinds) > 1:
            raise NotWritable(value)
        key_kind = key_kinds.pop() if key_kinds else TEXT
        value_kind = value_kinds.pop() if value_kinds else TEXT
        body = ', '.join('({}, {})'.format(key[1], item[1]) for key, item in pairs)
        return '&[({}, {})]'.format(key_kind, value_kind), '&[' + body + ']'
    raise NotWritable(value)


def module_text(source, module):
    """Return a module's Rust form, and the names it could not write."""
    lines = [HEADER.format(source=source)]
    skipped = []
    for constant, value in vars(module).items():
        if constant.startswith('_'):
            continue
        if inspect.isclass(value) and value.__module__ == module.__name__:
            lines.extend(class_text(constant, value, skipped))
            continue
        if not constant.isupper() or constant in HAND_WRITTEN:
            continue
        try:
            kind, expression = written(value)
        except NotWritable:
            skipped.append(constant)
            continue
        if kind in (TEXT, 'i64', 'f64', 'bool'):
            lines.append('pub const {}: {} = {};'.format(constant, kind, expression))
        else:
            lines.append('pub static {}: {} = {};'.format(constant, kind, expression))
    return '\n'.join(lines) + '\n', skipped


def class_text(name, value, skipped):
    """Return a class of constants as a Rust type with the same associated constants."""
    members = []
    for inner, item in vars(value).items():
        if inner.startswith('_') or not inner.isupper():
            continue
        try:
            kind, expression = written(item)
        except NotWritable:
            skipped.append('{}.{}'.format(name, inner))
            continue
        # An associated constant's references are written 'static, as Rust asks of them.
        members.append('    pub const {}: {} = {};'.format(inner, kind.replace('&', "&'static "), expression))
    if not members:
        return []
    return ['pub struct {};'.format(name), '', 'impl {} {{'.format(name), *members, '}', '']


def write_modules(*, folder, modules):
    """Write each (name, module) into the folder, with a mod.rs naming them, and return the names each could not write."""
    folder.mkdir(parents=True, exist_ok=True)
    names = []
    unwritten = {}
    for name, module in modules:
        source = module.__name__.replace('.', '/').replace('llamatron', 'src/llamatron', 1) + '.py'
        text, skipped = module_text(source, module)
        (folder / '{}.rs'.format(name)).write_text(text)
        names.append(name)
        if skipped:
            unwritten[name] = skipped
    # Generated, so the formatter leaves them as written, and a new generation is never only a reformatting.
    modules_text = '\n'.join('#[rustfmt::skip]\npub mod {};'.format(name) for name in names)
    (folder / 'mod.rs').write_text(HEADER.format(source=folder.name) + '\n' + modules_text + '\n')
    return unwritten


def write_enums(path):
    """Write each enum of ENUMS as an ordered list of every name it knows, aliases included, each (name, the name of the
    member it stands for, value), as Python's __members__ keeps them, and name the file in the folder's mod.rs. An alias
    such as IONIAN is the very member MAJOR, so a file that reads ionian writes major back, as the Python program does."""
    lines = [HEADER.format(source='the enums ScaleType and ChordType')]
    for constant, enum in ENUMS:
        members = [(name, member.name, member.value) for name, member in enum.__members__.items()]
        kind, expression = written(members)
        lines.append('pub static {}: {} = {};'.format(constant, kind, expression))
    path.write_text('\n'.join(lines) + '\n')
    module_list = path.parent / 'mod.rs'
    module_list.write_text(module_list.read_text() + '#[rustfmt::skip]\npub mod enums;\n')


PLUGINS_PACKAGE = 'llamatron.engine.generators'
PLUGIN_TEXTS_OUT = TOP / 'native' / 'strings' / 'src' / 'plugin_texts'


def plugin_texts():
    """Return each generator plugin's own words, its strings module, by the plugin's folder name."""
    plugins = importlib.import_module(PLUGINS_PACKAGE)
    found = []
    for folder in pkgutil.iter_modules(plugins.__path__):
        if folder.ispkg:
            found.append((folder.name, importlib.import_module('{}.{}.strings'.format(PLUGINS_PACKAGE, folder.name))))
    return found


SETTINGS_OUT = TOP / 'native' / 'model' / 'src' / 'schema' / 'generated' / 'settings.rs'
SETTINGS_TYPES = '''
/// A choice's value, or a setting's captured argument: text, a whole number, or a list of them.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Plain {
    Text(&'static str),
    Whole(i64),
    Float(f64),
    Flag(bool),
    Null,
    List(&'static [Plain]),
}

/// One setting's description, as the Python's model/schema/setting.py describes it.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Described {
    Flag { error: &'static str },
    Text { error: &'static str },
    WholeNumber { lowest: Option<i64>, highest: Option<i64>, error: &'static str },
    /// default None means LEFT_OUT, the setting left out of the file.
    Choice { choices: &'static [Plain], default: Option<Plain>, error: &'static str },
    TimeLength { most: (i64, i64), blank_allowed: bool },
    Checked { check: Check, arguments: &'static [Plain], needs_song: bool, nearest: Option<Nearest> },
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Setting {
    pub name: &'static str,
    pub described: Described,
}
'''


def setting_holders():
    """Return every class that holds settings, by the name its Rust table takes, in a steady order: the objects', then each
    generator plugin's settings."""
    import llamatron.model.objects as objects_package
    from llamatron.model.schema.generator_plugins import plugins
    found = []
    for info in pkgutil.iter_modules(objects_package.__path__):
        module = importlib.import_module('llamatron.model.objects.' + info.name)
        for name, value in vars(module).items():
            if inspect.isclass(value) and value.__module__ == module.__name__ and isinstance(getattr(value, 'SETTINGS', None), dict) and value.SETTINGS:
                found.append((snake(name).upper(), value))
    for plugin in plugins().values():
        found.append(('{}_PLUGIN'.format(plugin.name.upper()), plugin.settings))
    return found


def snake(name):
    """Return a CamelCase name as snake_case."""
    letters = []
    for place, letter in enumerate(name):
        if letter.isupper() and place:
            letters.append('_')
        letters.append(letter.lower())
    return ''.join(letters)


def function_variant(function):
    """Return the Rust variant naming a check function, from its module and name: the closures' outer function names them."""
    parts = function.__module__.split('.')
    module = parts[-1]
    if 'generators' in parts:
        # A plugin's function is named after its plugin as well as its module, since every plugin has a model module.
        module = '{}_{}'.format(parts[parts.index('generators') + 1], parts[-1])
    qualified = function.__qualname__.replace('.<locals>.', '_').lstrip('_')
    parts = '{}_{}'.format(module, qualified).replace('.', '_').split('_')
    return ''.join(part.capitalize() for part in parts if part)


def plain(value):
    """Return a choice or an argument as a Rust Plain."""
    if value is None:
        return 'Plain::Null'
    if isinstance(value, bool):
        return 'Plain::Flag({})'.format('true' if value else 'false')
    if isinstance(value, str):
        return 'Plain::Text({})'.format(literal(value))
    if isinstance(value, int):
        return 'Plain::Whole({})'.format(value)
    if isinstance(value, float):
        return 'Plain::Float({})'.format(repr(value))
    if isinstance(value, (tuple, list, frozenset)):
        return 'Plain::List(&[{}])'.format(', '.join(plain(item) for item in value))
    raise NotWritable(value)


def captured(function):
    """Return the plain values a closure captured, in order, which its Rust port takes as its arguments."""
    values = []
    for cell in function.__closure__ or ():
        try:
            values.append(plain(cell.cell_contents))
        except (NotWritable, ValueError):
            values.append('Plain::Null')
    return values


def described_text(described):
    """Return one setting's description as Rust."""
    kind = type(described).__name__
    if kind in ('Flag', 'Text'):
        return 'Described::{} {{ error: {} }}'.format(kind, literal(described._error))
    if kind == 'WholeNumber':
        bound = lambda value: 'None' if value is None else 'Some({})'.format(value)
        return 'Described::WholeNumber {{ lowest: {}, highest: {}, error: {} }}'.format(bound(described._lowest), bound(described._highest), literal(described._error))
    if kind == 'Choice':
        from llamatron.model.file import corrections
        default = 'None' if described._default is corrections.LEFT_OUT else 'Some({})'.format(plain(described._default))
        return 'Described::Choice {{ choices: &[{}], default: {}, error: {} }}'.format(', '.join(plain(choice) for choice in described._choices), default, literal(described._error))
    if kind == 'TimeLength':
        most = described._most
        return 'Described::TimeLength {{ most: ({}, {}), blank_allowed: {} }}'.format(getattr(most, 'numerator', most), getattr(most, 'denominator', 1), 'true' if described._blank_allowed else 'false')
    if kind == 'Checked':
        nearest = 'None' if described._nearest is None else 'Some(Nearest::{})'.format(function_variant(described._nearest))
        return 'Described::Checked {{ check: Check::{}, arguments: &[{}], needs_song: {}, nearest: {} }}'.format(
            function_variant(described._check), ', '.join(captured(described._check)), 'true' if described._needs_song else 'false', nearest)
    raise NotWritable(described)


def write_settings():
    """Write every class's settings, each described as the Python describes it, with the enums of the check and nearest
    functions their Rust port must handle every one of."""
    checks, nearests, tables = set(), set(), []
    for name, holder in setting_holders():
        rows = []
        for setting_name, described in holder.SETTINGS.items():
            if type(described).__name__ == 'Checked':
                checks.add(function_variant(described._check))
                if described._nearest is not None:
                    nearests.add(function_variant(described._nearest))
            rows.append('    Setting {{ name: {}, described: {} }},'.format(literal(setting_name), described_text(described)))
        tables.append('pub static {}: &[Setting] = &[\n{}\n];\n'.format(name, '\n'.join(rows)))
    lines = [HEADER.format(source='every class that holds settings, objects and generator plugins'), SETTINGS_TYPES]
    lines.append('/// Every check function a setting names; the Rust port matches each.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Check {\n' + ''.join('    {},\n'.format(check) for check in sorted(checks)) + '}\n')
    lines.append('/// Every function that finds a wrong value\'s nearest allowed one.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Nearest {\n' + ''.join('    {},\n'.format(nearest) for nearest in sorted(nearests)) + '}\n')
    lines.extend(tables)
    SETTINGS_OUT.write_text('\n'.join(lines))
    module_list = SETTINGS_OUT.parent / 'mod.rs'
    module_list.write_text(module_list.read_text() + '#[rustfmt::skip]\npub mod settings;\n')


def main():
    texts = [(info.name, importlib.import_module('llamatron.user_strings.' + info.name)) for info in pkgutil.iter_modules(package.__path__)]
    unwritten = write_modules(folder=OUT, modules=texts)
    unwritten.update(write_modules(folder=PLUGIN_TEXTS_OUT, modules=plugin_texts()))
    unwritten.update(write_modules(folder=SCHEMA_OUT, modules=SCHEMA_MODULES))
    write_settings()
    unwritten.update(write_modules(folder=FUNDAMENTALS_OUT, modules=FUNDAMENTALS_MODULES))
    write_enums(FUNDAMENTALS_OUT / 'enums.rs')
    unwritten.update(write_modules(folder=VALUES_OUT, modules=VALUES_MODULES))
    for name, skipped in unwritten.items():
        print('{}: not written: {}'.format(name, ', '.join(skipped)), file=sys.stderr)


if __name__ == '__main__':
    main()
